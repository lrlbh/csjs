# 磁性损耗计算，来自gemini，用于描述纹波电流提高时磁性损耗指数级增长
# gpt指出这是放屁,提出了一堆反驳，这里只记录两个看着靠谱的反驳
# 因为我觉得去年底开始gpt只有少部分时间段工作正常，会员也没用，新号倒是能正常几天
# 1、因为这个计算方式需要电流波形等于正弦波才成立，非正弦波需要切换公式
# 2、电感参数直流偏置非常严重，在叠加直流电压后，参数会劣化非常严重，需要带入直流偏置后的参数计算才可以

# 磁芯损耗 = K * (F ** X) * (B ** Y)
# K 材料常数 同样材料配方不同,K也不同,公开配方会被盗用？
# 锰锌铁氧体    MnZn Ferrite	损耗最低，多用于大型电感或变压器	             ★ (最低)
# 合金粉末	    Alloy Powder	常见的贴片功率电感（如一体成型电感），抗饱和好	  ★★★ (中等)
# 铁粉芯	    Iron Powder	    便宜但损耗极大，通常用于低频滤除噪音	         ★★★★★ (最高)
# F 开关频率
# x指数  材料对开关频率的敏感程度 通常在1.2~1.8     500k 也许等于 1.5
# B 磁感应强度变化量（单位：特斯拉 T）
# B = (电感量 * 纹波电流 ) / (绕组圈数 * 磁芯有效横截面积(单位m²))
# y指数  由材料决定 通常在2.0 到 2.7 之间

# 简易公式
# 磁芯损耗 = 具体电感型号系数 * (频率 ** X) * (纹波电流 ** Y)

# 简单评估
# 由上可知普通人能获取的数据，想方便的计算磁损耗是不太现实的
# 磁性损耗倍率 = 纹波电流倍率 ** Y
# 纹波电流提高1倍，磁性损耗大概提高  2 **2.5 = 5.65倍
# 纹波电流提高2倍，磁性损耗大概提高  3 **2.5 = 15.58倍
