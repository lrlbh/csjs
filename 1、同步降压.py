import math

输入电压 = 5.2  # 多个电压供电时取最大值
输出电压 = 3.3
输出最大电流 = 0.4  # 不一定满负载情况下取最大值
开关频率 = 1_200_000


# 允许更大纹波电流可以降低电感值，加快负载响应速度，不过有两个主要问题
# 1、需要加大输出电容补偿允许的最大输出电压纹波，以及电容发热
# 2、纹波电流提高会导致磁性损耗指数级提高
#   磁性损耗计算方式在下方，参数难以获得，而且ai也拒绝给出相对靠谱的大概值
#   不过数据手册都敢给出12v转3V3A，使用3.3uh同时不指定电感类型的推荐
#   说明当前芯片和常见电感场景下接近1.5A的纹波电流也不会导致损耗崩溃
#   而且其他输出电压参数，纹波电流还会大不少
允许电流最大纹波系数 = 0.20 # 0.3 ~ 0.4
允许最大输出纹波mv = 10
允许最大输入纹波mv = 30
###########################################################################

输入电流纹波 = (
    math.sqrt((输出电压 / 输入电压) * (1 - (输出电压 / 输入电压))) * 输出最大电流
)  # type: ignore
print(f"输入电流纹波: {输入电流纹波:.2f}A")
输入电容 = (
    (输出最大电流 / (开关频率 * (允许最大输入纹波mv / 1000)))
    * (输出电压 / 输入电压)
    * (1 - (输出电压 / 输入电压))
)
print(f"输入电容: {输入电容 * 1000_000:.2f}uF")

纹波电流 = 输出最大电流 * 允许电流最大纹波系数
print(f"纹波电流: {纹波电流:.2f}A")

print(f"饱和电流: {输出最大电流 + 纹波电流 / 2:.2F}A")

print(f"连续导通模式阈值: {纹波电流 / 2:.2F}A")

电感 = (输出电压 * (输入电压 - 输出电压)) / (输入电压 * 纹波电流 * 开关频率)
print(f"电感: {电感 * 1000_000:.2f}uH")


输出电容 = (输出电压 * (1 - 输出电压 / 输入电压)) / (
    8 * (开关频率**2) * 电感 * (允许最大输出纹波mv / 1000)
)

print(f"输出电容: {输出电容 * 1000_000:.2f}uF")

###################最大输出电容防止软启动失败###########################
启动时负载电流 = 0.5
平均启动电流限制 = 4  # 如果没有数据，取最大输出电流限制
TSS软起动时间ms = 1.2
