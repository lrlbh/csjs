# 计算
等效灵敏度 = 麦克风灵敏度db + (需要的最大音量db - 94)
有效电压 = 10 ** (等效灵敏度 / 20)
峰峰值电压 = 有效电压 * (2 * 2**0.5)
需要的放大倍数 = adc量程mv / 峰峰值电压

